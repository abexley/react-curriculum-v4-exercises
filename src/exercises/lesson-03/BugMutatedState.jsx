/*
  BUG #2 — State Issue

  This component displays a count and updates it when the button is clicked.
  However, the way the count is being changed causes the component to behave
  incorrectly.
*/

import { useState } from 'react';
export default function BugMutatedState() {
  const [count, setCount] = useState(0);

  function handleAdd() {
    setCount(count + 1);
  }

  return (
    <div>
      <p>Bug 2 Count: {count}</p>
      <button onClick={handleAdd}>Add 1</button>
    </div>
  );
}

// Explanation:
// The state was being changed directly by using count++, which mutates the
// current state value. React state should never be modified directly.
// Instead, use the state setter function (setCount) to create and store
// the new value. Calling setCount(count + 1) lets React detect the
// change and re-render the component correctly.
